"use client";

import Link from "next/link";
import { useRef, useState } from "react";
import { Mail, Phone, Send, UserRound } from "lucide-react";
import { Provenance } from "@/components/provenance";
import { Button } from "@/components/ui/button";
import type { Provenance as Kind } from "@/lib/types";

interface Citation {
  code: string;
  kind: "coverage" | "endorsement" | "exclusion";
  name: string;
  limit_usd?: number | null;
  present?: boolean;
}
interface Answer {
  answer_plain: string;
  citations: Citation[];
  cited_glossary_terms: string[];
  confidence: "high" | "medium" | "low";
  needs_agent: boolean;
  suggested_actions: string[];
  provenance: Kind;
  source: string;
  disclaimer: string;
  agent: { name: string; email: string; agency: string };
}
type Msg = { role: "user"; text: string } | { role: "assistant"; answer: Answer } | { role: "error"; text: string };

const CHIP_LABEL = { coverage: "Coverage", endorsement: "Add-on", exclusion: "Left out" } as const;

export function AskChat({ accountId, starters, agentPhone }: { accountId: string; starters: string[]; agentPhone: string | null }) {
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [q, setQ] = useState("");
  const [busy, setBusy] = useState(false);
  const end = useRef<HTMLDivElement>(null);

  async function ask(text: string) {
    const question = text.trim();
    if (question.length < 3 || busy) return;
    setQ("");
    setBusy(true);
    setMsgs((m) => [...m, { role: "user", text: question }]);
    try {
      const r = await fetch("/backend/api/v1/assistant/ask", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ account_id: accountId, question }),
      });
      const body = await r.json();
      setMsgs((m) => [...m, r.ok ? { role: "assistant", answer: body } : { role: "error", text: body.detail ?? "Something went wrong." }]);
    } catch {
      setMsgs((m) => [...m, { role: "error", text: "Could not reach the assistant. Your agent can help in the meantime." }]);
    } finally {
      setBusy(false);
      setTimeout(() => end.current?.scrollIntoView({ behavior: "smooth", block: "end" }), 50);
    }
  }

  return (
    <div className="space-y-4">
      {msgs.length === 0 && (
        <section aria-labelledby="starters-h" className="space-y-2">
          <h2 id="starters-h" className="text-sm font-semibold text-muted">
            Try asking
          </h2>
          <ul className="flex flex-wrap gap-2">
            {starters.map((s) => (
              <li key={s}>
                <button
                  type="button"
                  onClick={() => ask(s)}
                  data-testid="starter"
                  className="min-h-[44px] rounded-full border border-line bg-surface px-4 py-2 text-left text-sm font-medium hover:bg-surface-2"
                >
                  {s}
                </button>
              </li>
            ))}
          </ul>
        </section>
      )}

      <div className="space-y-3" role="log" aria-live="polite" aria-label="Conversation">
        {msgs.map((m, i) =>
          m.role === "user" ? (
            <p key={i} className="ml-auto max-w-[85%] rounded-2xl rounded-br-sm bg-accent-strong px-4 py-2 text-sm text-white dark:text-[#06201f]" data-testid="user-msg">
              {m.text}
            </p>
          ) : m.role === "error" ? (
            <p key={i} role="alert" className="rounded-xl bg-clay-soft p-3 text-sm text-clay-text">
              {m.text}
            </p>
          ) : (
            <article key={i} className="max-w-[95%] space-y-3 rounded-2xl rounded-bl-sm border border-line bg-surface p-4 text-sm" data-testid="answer">
              <div className="flex flex-wrap items-center gap-2">
                <Provenance kind={m.answer.provenance} detail={m.answer.source === "gemini" ? "Generated by AI from your policy summary." : "Composed by rules from your policy summary (no AI used)."} />
                <span className="text-xs text-muted">Confidence: {m.answer.confidence}</span>
              </div>
              <p className="leading-relaxed" data-testid="answer-text">
                {m.answer.answer_plain}
              </p>
              {m.answer.citations.length > 0 && (
                <div>
                  <p className="text-xs font-semibold text-muted">From your policy summary</p>
                  <ul className="mt-1 flex flex-wrap gap-2">
                    {m.answer.citations.map((c) => (
                      <li key={c.code}>
                        <Link
                          href={`/coverage#${c.code}`}
                          data-testid="citation-chip"
                          className="inline-flex min-h-[44px] items-center gap-1 rounded-full border border-accent/50 bg-accent-soft px-3 text-xs font-semibold text-accent-text"
                        >
                          <span className="text-[10px] uppercase opacity-80">{CHIP_LABEL[c.kind]}</span> {c.name}
                        </Link>
                      </li>
                    ))}
                  </ul>
                </div>
              )}
              {m.answer.cited_glossary_terms.length > 0 && <p className="text-xs text-muted">Glossary: {m.answer.cited_glossary_terms.join(", ")}</p>}
              {m.answer.suggested_actions.length > 0 && (
                <ul className="list-disc space-y-1 pl-5">
                  {m.answer.suggested_actions.map((a) => (
                    <li key={a}>{a}</li>
                  ))}
                </ul>
              )}
              <div className="rounded-lg bg-surface-2 p-3" data-testid="handoff">
                <p className="flex items-center gap-2 font-semibold">
                  <UserRound className="h-4 w-4" aria-hidden /> {m.answer.needs_agent ? "Talk to your agent about this" : "Want to confirm with your agent?"}
                </p>
                <p className="text-xs text-muted">
                  {m.answer.agent.name} · {m.answer.agent.agency}
                </p>
                <p className="mt-1 flex flex-wrap gap-2">
                  <Button asChild size="sm" variant="secondary">
                    <a href={`mailto:${m.answer.agent.email}?subject=${encodeURIComponent("Coverage question")}`}>
                      <Mail className="h-4 w-4" aria-hidden /> Email
                    </a>
                  </Button>
                  {agentPhone && (
                    <Button asChild size="sm" variant="secondary">
                      <a href={`tel:${agentPhone}`}>
                        <Phone className="h-4 w-4" aria-hidden /> Call
                      </a>
                    </Button>
                  )}
                </p>
              </div>
              <p className="text-xs text-muted">{m.answer.disclaimer}</p>
            </article>
          ),
        )}
        {busy && (
          <p className="text-sm text-muted" role="status">
            Looking through your policy summary…
          </p>
        )}
        <div ref={end} />
      </div>

      <form
        onSubmit={(e) => {
          e.preventDefault();
          void ask(q);
        }}
        className="sticky bottom-20 flex gap-2 rounded-card border border-line bg-surface p-2 shadow-lift lg:bottom-4"
      >
        <label htmlFor="ask-input" className="sr-only">
          Your question about your coverage
        </label>
        <input
          id="ask-input"
          value={q}
          onChange={(e) => setQ(e.target.value)}
          maxLength={500}
          placeholder="Ask about your coverage…"
          className="min-h-[44px] flex-1 rounded-lg bg-transparent px-3 text-sm outline-none placeholder:text-muted"
          autoComplete="off"
        />
        <Button type="submit" disabled={busy || q.trim().length < 3} aria-label="Send question">
          <Send className="h-4 w-4" aria-hidden />
        </Button>
      </form>
    </div>
  );
}
