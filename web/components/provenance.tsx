import { cn } from "@/lib/utils";
import type { Provenance as Kind } from "@/lib/types";
import { Tip } from "@/components/ui/tooltip";

const STYLE: Record<Kind, string> = {
  LIVE: "bg-saguaro-soft text-saguaro-text border-saguaro/40",
  HISTORIC: "bg-surface-2 text-ink border-line",
  SYNTHETIC: "bg-amber-soft text-amber-text border-amber/50",
  SIMULATED: "bg-clay-soft text-clay-text border-clay/50",
  AI: "bg-accent-soft text-accent-text border-accent/50",
};

const EXPLAIN: Record<Kind, string> = {
  LIVE: "Live from the National Weather Service / Open-Meteo.",
  HISTORIC: "From archives: Open-Meteo history, NOAA Storm Events, FEMA National Risk Index.",
  SYNTHETIC: "Invented demo data (personas, policies, assets, claims). Not a real person or policy.",
  SIMULATED: "Injected by the Scenario Director or a simulated device. Not a real event.",
  AI: "Wording generated by AI from your policy data. Your agent confirms coverage.",
};

/** Mandatory on every data element (CLAUDE.md truthfulness rules). */
export function Provenance({ kind, detail, className }: { kind: Kind; detail?: string; className?: string }) {
  return (
    <Tip content={`${EXPLAIN[kind]}${detail ? ` ${detail}` : ""}`}>
      <span
        tabIndex={0}
        className={cn(
          "inline-flex min-h-[20px] cursor-help items-center rounded-full border px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide",
          STYLE[kind],
          className,
        )}
      >
        {kind}
      </span>
    </Tip>
  );
}
